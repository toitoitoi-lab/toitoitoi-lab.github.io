//   2つが重なる所 → ここから始める（支援する人も楽しく、子どもにも届く）。
//   子どもには届くが、支援する人が得意でない所 → 大人が子どもに合わせる。ICT・AIで補う。
//   支援する人は得意だが、子どもには負担な所 → 形を変えて使う。
//   結果はベン図（あなたの得意／この子に届く）と、明日の一手、強みのことば（客観的な言いかえ）で示す。
// 用語：子どもの「わかり方」＝その子がいちばん負担少なく情報を受け取れる形。支援する人の「伝え方」＝ふだん楽しく自然にとっている伝える形。
// 第2部（任意）：関わり方のくせ 4つの軸（2択）。2択のどちらにも優劣はない。長所は場面によって短所に、短所は場面によって長所になる。
//
// s: 支援する人の問い（l = 左の端にあてはまる人の文、r = 右の端）
// c: 子どもの様子（支援する人が、見ている事実から答える。本人が答えてもよい）
// adv: 結果の文。ll = 両方とも左、rr = 両方とも右、lr = 支援者が左・子どもが右、rl = その逆
//      各 { ikasu: 強みを生かすと, ki: 気をつけたいこと, soudan: 相談するなら }

